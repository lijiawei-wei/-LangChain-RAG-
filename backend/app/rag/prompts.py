# ============================================================
# 上下文拼装模板
# ============================================================
# 每个分块的呈现格式。编号写死在文本里（而不是指望模型自己数），
# 这样模型只需要照着抄，标注出错率会低很多。
CONTEXT_CHUNK_TEMPLATE = "[{index}] {content}\n    出处：{source}"


def format_context(citations: list[dict]) -> str:
    """把检索到的分块拼成给模型看的参考资料。

    每个分块前面带一个编号 [1] [2]…，后面跟一行来源信息。
    编号是「烘焙」进上下文文本里的，不是让模型自己去数——
    实测这样标注准确率明显更高。
    """
    if not citations:
        return "（没有检索到相关资料）"

    blocks = []
    for item in citations:
        source = item.get("source_label") or item.get("filename", "未知来源")
        blocks.append(
            CONTEXT_CHUNK_TEMPLATE.format(
                index=item["index"],
                content=item["text"],
                source=source,
            )
        )
    return "\n\n".join(blocks)
