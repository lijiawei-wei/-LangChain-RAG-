"""寒暄类问题的识别。

====================================================================
为什么需要这个模块
====================================================================
商品知识库里当然不会有「你是谁」的答案，所以这类问题检索必然为空，
以前会走到"没有找到相关资料"那条兜底分支。实测效果是：

    问「你好」    → 检索恰好捞到了耳机资料 → 大模型回「你好！有什么关于
                    声动 Buds Pro 耳机的问题，我很乐意帮你解答 😊」很自然
    问「你是谁」  → 检索为空 → 回「抱歉，我在知识库里没有找到……」
                    看着像系统坏了

同一套系统，两种表现，差别只在于检索有没有恰好捞到东西——**这很随机**。

更麻烦的是：检索阈值从 0.15 调高到 0.45 之后（这个调整本身是对的，
给无关问题省了 41% 的上下文），会有更多这类问题落进"检索为空"那条路，
问题变得更明显。

所以这里单独拦一道：**在检索之前先判断是不是寒暄**，是就直接给一段
固定回复，不检索、不调模型。成本为零、响应是瞬时的、结果稳定。

====================================================================
这类做法在 RAG 里叫什么
====================================================================
叫「意图路由」（intent routing）：先用一层轻量的判断决定走哪条链路。
它是 RAG 系统的常见组成部分——不是所有输入都值得走完整的检索生成流程，
硬走反而会因为"检索不到"给出很差的体验。

反面做法是让大模型来兜底（检索为空时也调一次模型自由发挥）。
那样每题要多花 2~4 秒和一次生成调用，而且回答不确定。
寒暄这类问题本来就是有限可枚举的，用规则更划算。
"""

from __future__ import annotations

import re

# 匹配时先要把标点和空白去掉，否则「你好，」和「你好」会被当成两种写法。
#
# 用三引号而不是普通引号：这段正则里既有英文单双引号又有方括号，
# 用普通引号写要加一堆反斜杠转义，很容易漏掉一两个变成转义警告
_PUNCTUATION = re.compile(r"""[\s，。！？、；：“”‘’（）《》【】…—～~,.!?;:"'()\[\]<>_-]+""")

# ============================================================
# 触发词表
# ============================================================
# 键是类别名，值是这一类问题的触发词。
# 类别名会和 prompts.py 里的回复模板对应上。
SMALLTALK_PATTERNS: dict[str, tuple[str, ...]] = {
    "greeting": (
        "你好", "您好", "哈喽", "哈啰", "嗨", "早上好", "中午好",
        "下午好", "晚上好", "在吗", "在么", "在不在",
        "hi", "hello", "hey",
    ),
    "identity": (
        "你是谁", "你叫什么", "你叫啥", "你是什么", "你的名字",
        "介绍一下你", "自我介绍", "你是什么东西", "你是干嘛的", "你是做什么的",
    ),
    "capability": (
        "你能做什么", "你会什么", "你能干什么", "你能帮我做什么",
        "你有什么功能", "有什么功能", "能做什么", "怎么用", "如何使用",
        "帮助", "help",
    ),
    "thanks": (
        "谢谢", "多谢", "感谢", "辛苦了", "谢了", "3q",
        "thanks", "thank you", "thx",
    ),
    "farewell": (
        "再见", "拜拜", "回头见", "下次见", "bye", "goodbye",
    ),
}

# 去掉触发词之后，剩余内容超过这个长度就不算寒暄。
#
# **这个阈值是整个模块的关键**，它防的是这种误判：
#
#     「你好，这款手机多少钱」  ← 含「你好」，但它是个正经的商品问题
#     「你是什么牌子的」        ← 含「你是什么」，但问的是商品
#
# 光看"包不包含触发词"会把它们误判成寒暄，用户就会看到一段自我介绍、
# 而他要问的商品问题被吞掉了——这比原来的问题更严重。
#
# 取 2 是因为中文的语气词通常只有一两个字（啊、呀、呢、哦、啦），
# 去掉触发词后只剩这些，说明用户确实只是打个招呼。
_MAX_REMAINDER = 2


def normalize(text: str) -> str:
    """去掉标点、空白，英文转小写，便于统一匹配。"""
    return _PUNCTUATION.sub("", text).lower()


def match_smalltalk(question: str | None) -> str | None:
    """判断问题是不是寒暄，是的话返回类别名，否则返回 None。

    匹配规则分两步，**缺一不可**：
      1. 问题里包含某个触发词
      2. 把所有触发词都去掉之后，剩下的内容不超过 2 个字

    只有两步都满足才算寒暄。第 2 步是防误判的关键，理由见 _MAX_REMAINDER。
    """
    if not question:
        return None

    text = normalize(question)
    if not text:
        return None

    # 长问题基本不可能是寒暄，先快速挡掉，省得白跑一遍匹配。
    # 但要注意不能挡得太狠：「你好，在吗，我想问一下你们这个手机」
    # 这种带寒暄的长句本来就该走正常问答，挡掉是对的
    if len(text) > 30:
        return None

    for category, patterns in SMALLTALK_PATTERNS.items():
        if not any(p in text for p in patterns):
            continue

        # 把这一个类别的所有触发词都从文本里去掉。
        # 为什么要去掉"所有"而不是只去掉命中的那个：
        # 「你好，在吗」同时含两个触发词，只去掉一个的话会剩下「在吗」，
        # 长度 2 刚好卡在边界上，容易出意外
        remainder = text
        for p in patterns:
            remainder = remainder.replace(p, "")

        if len(remainder) <= _MAX_REMAINDER:
            return category

    return None


def is_smalltalk(question: str | None) -> bool:
    """只是想知道"是不是寒暄"，不关心是哪一类时用这个。"""
    return match_smalltalk(question) is not None
